export function getBrowserLanguage(): Language {
  if (typeof localStorage !== 'undefined') {
    const stored = localStorage.getItem('snake_samurai_lang');
    if (stored === 'zh-CN' || stored === 'zh-TW' || stored === 'ja' || stored === 'en' || stored === 'ko' || stored === 'fr' || stored === 'nl') return stored;
  }
  const nav = typeof navigator !== 'undefined' ? navigator.language : 'zh-CN';
  if (nav.startsWith('ja')) return 'ja';
  if (nav.startsWith('en')) return 'en';
  if (nav.startsWith('zh-TW') || nav.startsWith('zh-HK')) return 'zh-TW';
  return 'zh-CN';
}

export function saveLanguagePreference(lang: Language) {
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem('snake_samurai_lang', lang);
  }
}
