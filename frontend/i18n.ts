export const getBrowserLanguage = (): Language => {
  try {
    const saved = localStorage.getItem('kazeabc_language');
    if (saved && ['zh-CN', 'ja', 'en', 'zh-TW', 'ko', 'fr', 'nl'].includes(saved)) return saved as Language;
  } catch {
    // Storage may be unavailable in a restricted browser context.
  }
  const lang = navigator.language;
  if (lang.startsWith('zh-CN') || lang === 'zh') return 'zh-CN';
  if (lang.startsWith('zh-TW') || lang.startsWith('zh-HK')) return 'zh-TW';
  if (lang.startsWith('ja')) return 'ja';
  if (lang.startsWith('ko')) return 'ko';
  if (lang.startsWith('fr')) return 'fr';
  if (lang.startsWith('nl')) return 'nl';
  return 'en';
};

export const saveLanguagePreference = (language: Language) => {
  try {
    localStorage.setItem('kazeabc_language', language);
  } catch {
    // The current session still switches language even without persistence.
  }
};
