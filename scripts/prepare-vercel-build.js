import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { execSync } from 'child_process';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const repoRoot = path.resolve(__dirname, '..');
const frontendDir = path.resolve(repoRoot, 'frontend');
const frontendDist = path.resolve(frontendDir, 'dist');

let commitCount = process.env.VITE_REPO_COMMIT_COUNT;
if (!commitCount) {
  try {
    commitCount = execSync('git rev-list --count HEAD', { cwd: repoRoot, encoding: 'utf8' }).trim();
  } catch (e) {
    commitCount = '178';
  }
}
process.env.VITE_REPO_COMMIT_COUNT = commitCount;
console.log(`Step 1: Running vite build in frontend (Commit Count: v${commitCount})...`);
execSync('npm run build', { cwd: frontendDir, stdio: 'inherit', env: { ...process.env, VITE_REPO_COMMIT_COUNT: commitCount } });

if (!fs.existsSync(frontendDist)) {
  console.error('Error: frontend/dist was not generated by vite build!');
  process.exit(1);
}

function copyDirSync(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  const entries = fs.readdirSync(src, { withFileTypes: true });
  for (const entry of entries) {
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDirSync(srcPath, destPath);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

const targets = [
  path.resolve(repoRoot, 'dist'),
  path.resolve(repoRoot, 'static'),
  path.resolve(frontendDir, 'static'),
  path.resolve(frontendDir, '.vercel/output/static'),
  path.resolve(repoRoot, '.vercel/output/static')
];

console.log('Step 2: Replicating build output to all Vercel target locations...');
for (const target of targets) {
  copyDirSync(frontendDist, target);
  console.log(` -> Copied dist to ${target}`);
}

const vercelConfig = {
  version: 3,
  routes: [
    { handle: 'filesystem' },
    { src: '/(.*)', dest: '/index.html' }
  ]
};

const configPaths = [
  path.resolve(frontendDir, '.vercel/output/config.json'),
  path.resolve(repoRoot, '.vercel/output/config.json')
];

for (const configPath of configPaths) {
  fs.mkdirSync(path.dirname(configPath), { recursive: true });
  fs.writeFileSync(configPath, JSON.stringify(vercelConfig, null, 2), 'utf8');
  console.log(` -> Written config.json to ${configPath}`);
}

console.log('Build preparation completed successfully!');
